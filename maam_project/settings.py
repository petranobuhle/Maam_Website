# --- Database ----------------------------------------------------------------
# Production: set DATABASE_URL to the Neon PostgreSQL connection string, e.g.
#   postgresql://USER:PASSWORD@HOST/DBNAME?sslmode=require
# Local development: leave DATABASE_URL unset to use SQLite (db.sqlite3).
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
DB_ENGINE = os.environ.get("DB_ENGINE", "django.db.backends.sqlite3")
if DATABASE_URL:
    DATABASES = {
        "default": dj_database_url.parse(
            DATABASE_URL,
            conn_max_age=int(os.environ.get("DB_CONN_MAX_AGE", "60") or "60"),
            # Neon can pause when idle; check reused connections before each request.
            conn_health_checks=True,
            # Encrypt the connection to the database server (Neon requires SSL).
            ssl_require=env_bool("DB_SSL_REQUIRE", True),
        )
    }
elif not DEBUG and not env_bool("ALLOW_SQLITE_IN_PRODUCTION", False):
    # Render's disk is wiped on every deploy, so a SQLite file there would lose all data.
    raise ImproperlyConfigured("Set DATABASE_URL to the Neon PostgreSQL connection string when DEBUG is off.")
elif DB_ENGINE == "django.db.backends.sqlite3":
    DATABASES = {
        "default": {
            "ENGINE": DB_ENGINE,
            "NAME": os.environ.get("DB_NAME", str(BASE_DIR / "db.sqlite3")),
        }
    }
else:
    DATABASES = {
        "default": {
            "ENGINE": DB_ENGINE,
            "NAME": os.environ.get("DB_NAME", "maam"),
            "USER": os.environ.get("DB_USER", "postgres"),
            "PASSWORD": os.environ.get("DB_PASSWORD", "postgres"),
            "HOST": os.environ.get("DB_HOST", "localhost"),
            "PORT": os.environ.get("DB_PORT", "5432"),
        }
    }

